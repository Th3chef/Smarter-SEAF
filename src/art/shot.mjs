import { chromium } from 'playwright-core';
const [,, page_, out, w, h] = process.argv;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell', args: ['--allow-file-access-from-files', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: +(w||900), height: +(h||900) } });
p.on('console', m => console.log('console:', m.text()));
p.on('pageerror', e => console.log('error:', e.message));
await p.goto('http://127.0.0.1:8765/' + page_);
await p.waitForFunction(() => window.DONE === true, null, { timeout: 120000 });
console.log(JSON.stringify(await p.evaluate(() => window.INFO)).slice(0, 2000));
await p.screenshot({ path: out, omitBackground: true });
await b.close();
